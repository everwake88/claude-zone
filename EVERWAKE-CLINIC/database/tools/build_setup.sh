#!/usr/bin/env bash
# Joins every migration into one file to paste into Supabase's SQL editor:
#   ./database/tools/build_setup.sh   →   everwake_clinic_supabase_setup.sql
set -euo pipefail
cd "$(dirname "$0")/.."
out=../everwake_clinic_supabase_setup.sql
{
  echo "-- Everwake Clinic · the whole database in one paste (Supabase SQL editor)."
  echo "-- Generated by database/tools/build_setup.sh — do not edit; edit database/migrations/ and run it again."
  for f in migrations/*.sql; do
    echo; echo "-- ================= $(basename "$f") ================="; echo
    cat "$f"
  done
} > "$out"
echo "wrote $(wc -l < "$out") lines to $(cd .. && pwd)/everwake_clinic_supabase_setup.sql"
