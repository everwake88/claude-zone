export type Lang = 'ar' | 'en';
export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = lang === 'en' ? en : ar;
  return (key, vars) => {
    let s: string = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

const MONTHS = {
  ar: ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'],
  en: ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December']
};
export const monthName = (lang: Lang, m: number) => MONTHS[lang][m - 1];
// "2026-10" or a date → "أكتوبر 2026" / "October 2026"
export function periodLabel(lang: Lang, period: string | Date): string {
  const s = typeof period === 'string' ? period : period.toISOString();
  const [y, m] = s.slice(0, 7).split('-').map(Number);
  return `${monthName(lang, m)} ${y}`;
}
